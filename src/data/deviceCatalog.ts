export type CameraBrand = 'Sony' | 'Canon' | 'Nikon' | 'Fujifilm';
export type SensorFormat = 'Full Frame' | 'APS-C' | 'Medium Format';
export type LensCoverage = SensorFormat;

export interface CameraBody {
  id: string;
  brand: CameraBrand;
  model: string;
  mount: string;
  sensorFormat: SensorFormat;
  /** FrameSage 人像工作流推荐值，不是厂商原生 ISO 上限。 */
  isoLimit: number;
  /** 供既有推荐引擎使用的近似参考值；展示时必须标为参考。 */
  dynamicRange: number;
  dynamicRangeReference: string;
  colorBias: string;
  notes: string;
}

export interface CameraLens {
  id: string;
  brand: CameraBrand;
  model: string;
  mount: string;
  coverage: LensCoverage;
  /** 铭牌物理焦段。 */
  nativeFocalLength: string;
  /** 供既有规则引擎使用的代表焦段（变焦取常用人像档，裁切系统取等效视角）。 */
  focalLength: number;
  maxAperture: number;
  bokehFactor: number;
  minFocus: number;
  stabilization: boolean;
  notes: string;
}

